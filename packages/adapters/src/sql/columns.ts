/**
 * A comma-separated select list of every column of `table`, in schema order;
 * each column qualified with `alias` when one is given (multi-table queries).
 */
export function columnList(table: TableName, alias?: string): string {
	const columns: readonly string[] = TABLE_COLUMNS[table];
	return alias === undefined
		? columns.join(", ")
		: columns.map((column) => `${alias}.${column}`).join(", ");
}
