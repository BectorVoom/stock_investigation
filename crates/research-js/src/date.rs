/// V8 `IsWhiteSpace` (ECMA-262 WhiteSpace: TAB, VT, FF, SP, NBSP, ZWNBSP, Zs).
const fn is_white_space(unit: u32) -> bool {
	matches!(
		unit,
		0x09 | 0x0B | 0x0C | 0x20 | 0xA0 | 0x1680 | 0x2000
			..=0x200A | 0x202F | 0x205F | 0x3000 | 0xFEFF
	)
}

/// V8 `IsWhiteSpaceOrLineTerminator`.
const fn is_white_space_or_line_terminator(unit: u32) -> bool {
	is_white_space(unit) || matches!(unit, 0x0A | 0x0D | 0x2028 | 0x2029)
}

