//! V8's `Date.parse` and `Date.prototype.toISOString`.
//!
//! The runner feeds untrusted text to `Date.parse`: feed timestamps
//! (`parseFeedTimestamp`), `article:published_time` meta tags, ISO instants
//! from its own clock. V8 accepts far more than ECMA-262's date-time format:
//! when the ES5 ISO parser does not consume the whole string it hands the
//! rest to a legacy, Safari-compatible parser (`src/date/dateparser*.{h,cc}`
//! in V8). Both are ported here state for state, including their quirks:
//! `Feb 30` rolls over to `Mar 2`, `24:00` is the next midnight, seconds `60`
//! and minutes `60` in legacy text become a date component that is then
//! ignored, two-digit-valued legacy years map to 2000–2049 / 1950–1999, a
//! NUL character ends the input, more than nine digits of a number are
//! skipped, and a time without a zone is local time.
//!
//! The local time zone is a parameter ([`LocalTimeZone`]); [`parse`] uses
//! the operating system's zone like Node does. Every rule is checked against
//! `vectors/js/date-parse.json`, generated by Node (`scripts/vectors/date.ts`)
//! under fixed zones.

use chrono::{DateTime, Local, LocalResult, Offset, TimeZone};

/// Milliseconds per day.
const MS_PER_DAY: f64 = 86_400_000.0;
/// ECMA-262 time values span ±10^8 days around the epoch.
const MAX_TIME_MS: f64 = 8.64e15;
/// V8 accepts a local time up to ten days beyond the range before converting
/// it to UTC (`DateCache::kMaxTimeBeforeUTCInMs`).
const MAX_TIME_BEFORE_UTC_MS: f64 = MAX_TIME_MS + 864_000_000.0;
/// V8's "no value" marker in its date composers (`kMaxInt`).
const NONE: i32 = i32::MAX;
/// `ReadUnsignedNumeral` keeps this many significant digits, skips the rest.
const MAX_SIGNIFICANT_DIGITS: usize = 9;
/// `Smi::kMaxValue` of Node's V8 (31-bit Smis): a zone offset above it in
/// seconds makes the whole string invalid (`+596524:` is rejected).
const SMI_MAX_VALUE: u32 = 0x7FFF_FFFF;

/// The local time zone, as V8's date cache asks it.
pub trait LocalTimeZone: Sync {
	/// Offset (local minus UTC, in ms) that applies to the local wall-clock
	/// time `local_ms` (milliseconds since 1970-01-01T00:00 read as a wall
	/// clock). In a gap or a fold the offset before the transition wins, as
	/// with ICU's `getOffsetFromLocal(FORMER, FORMER)`.
	fn offset_from_local_ms(&self, local_ms: i64) -> i64;
}

/// UTC (`TZ=UTC`).
#[derive(Clone, Copy, Debug, Default)]
pub struct Utc;

impl LocalTimeZone for Utc {
	fn offset_from_local_ms(&self, _local_ms: i64) -> i64 {
		0
	}
}

/// A zone with one constant offset (e.g. `Etc/GMT-9`).
#[derive(Clone, Copy, Debug)]
pub struct FixedOffset {
	offset_ms: i64,
}

impl FixedOffset {
	/// A zone `minutes` east of UTC.
	#[must_use]
	pub fn east_minutes(minutes: i32) -> Self {
		Self {
			offset_ms: i64::from(minutes) * 60_000,
		}
	}
}

impl LocalTimeZone for FixedOffset {
	fn offset_from_local_ms(&self, _local_ms: i64) -> i64 {
		self.offset_ms
	}
}

/// The operating system's zone (`TZ`, else `/etc/localtime`), which is what
/// Node's ICU uses for the runner.
#[derive(Clone, Copy, Debug, Default)]
pub struct SystemTimeZone;

impl LocalTimeZone for SystemTimeZone {
	fn offset_from_local_ms(&self, local_ms: i64) -> i64 {
		let seconds = local_ms.div_euclid(1000);
		let Some(wall) = DateTime::from_timestamp(seconds, 0).map(|utc| utc.naive_utc()) else {
			return 0;
		};
		match Local.offset_from_local_datetime(&wall) {
			LocalResult::Single(offset) => i64::from(offset.fix().local_minus_utc()) * 1000,
			// A fold: the earlier instant, i.e. the offset before the transition.
			LocalResult::Ambiguous(earliest, _) => {
				i64::from(earliest.fix().local_minus_utc()) * 1000
			}
			// A gap: the offset in force before the transition. Transitions are
			// never closer than a day, so the offset a day earlier is that one.
			LocalResult::None => DateTime::from_timestamp(seconds - 86_400, 0).map_or(0, |utc| {
				i64::from(
					Local
						.offset_from_utc_datetime(&utc.naive_utc())
						.fix()
						.local_minus_utc(),
				) * 1000
			}),
		}
	}
}

/// `Date.parse(text)` in the operating system's time zone: epoch
/// milliseconds, or NaN when V8 rejects the text.
#[must_use]
pub fn parse(text: &str) -> f64 {
	parse_in(text, &SystemTimeZone)
}

/// `Date.parse(text)` with `zone` as the local time zone.
#[must_use]
pub fn parse_in(text: &str, zone: &dyn LocalTimeZone) -> f64 {
	let units: Vec<u16> = text.encode_utf16().collect();
	let Some(fields) = parse_fields(&units) else {
		return f64::NAN;
	};
	let day = make_day(fields.year, fields.month, fields.day);
	let time = make_time(
		fields.hour,
		fields.minute,
		fields.second,
		fields.millisecond,
	);
	let mut date = make_date(day, time);
	match fields.utc_offset_seconds {
		None => {
			if !(-MAX_TIME_BEFORE_UTC_MS..=MAX_TIME_BEFORE_UTC_MS).contains(&date) {
				return f64::NAN;
			}
			let Some(local_ms) = exact_i64(date) else {
				return f64::NAN;
			};
			let offset = zone.offset_from_local_ms(local_ms);
			date = to_f64(local_ms - offset);
		}
		Some(offset) => {
			date -= f64::from(offset) * 1000.0;
			if !(-MAX_TIME_MS..=MAX_TIME_MS).contains(&date) {
				return f64::NAN;
			}
		}
	}
	time_clip(date)
}

/// `Date.parse(text)` with `zone` as the local zone, as integral epoch
/// milliseconds (`TimeClip` makes every finite result an integer within
/// ±8.64e15); `None` where JavaScript gives NaN.
#[must_use]
pub fn parse_epoch_ms(text: &str, zone: &dyn LocalTimeZone) -> Option<i64> {
	exact_i64(parse_in(text, zone))
}

/// `new Date(ms).toISOString()` for integral milliseconds; `None` where
/// JavaScript throws a `RangeError` (beyond ±8.64e15).
#[must_use]
pub fn epoch_ms_to_iso(ms: i64) -> Option<String> {
	// Checked first so the conversion below stays exact (|ms| <= 2^53).
	if ms.unsigned_abs() > 8_640_000_000_000_000 {
		return None;
	}
	to_iso_string(to_f64(ms))
}

/// ECMA-262 `TimeClip`: NaN outside ±8.64e15 ms, else the integer part
/// (`-0` becomes `+0`).
#[must_use]
pub fn time_clip(time: f64) -> f64 {
	if (-MAX_TIME_MS..=MAX_TIME_MS).contains(&time) {
		time.trunc() + 0.0
	} else {
		f64::NAN
	}
}

/// `new Date(time).toISOString()`: `YYYY-MM-DDTHH:mm:ss.sssZ`, with a signed
/// six-digit year outside 0000–9999. `None` where JavaScript throws a
/// `RangeError` (NaN or a time value out of range).
#[must_use]
pub fn to_iso_string(time: f64) -> Option<String> {
	let clipped = time_clip(time);
	let ms = exact_i64(clipped)?;
	let days = ms.div_euclid(86_400_000);
	let in_day = ms.rem_euclid(86_400_000);
	let (year, month, day) = civil_from_days(days);
	let hour = in_day / 3_600_000;
	let minute = in_day / 60_000 % 60;
	let second = in_day / 1000 % 60;
	let milli = in_day % 1000;
	let year_text = if (0..=9999).contains(&year) {
		format!("{year:04}")
	} else if year < 0 {
		format!("-{:06}", year.unsigned_abs())
	} else {
		format!("+{year:06}")
	};
	Some(format!(
		"{year_text}-{month:02}-{day:02}T{hour:02}:{minute:02}:{second:02}.{milli:03}Z"
	))
}

/// `value` as an `i64` when it is an integer of magnitude at most 2^53.
#[allow(clippy::cast_possible_truncation)]
fn exact_i64(value: f64) -> Option<i64> {
	if !value.is_finite() || value.trunc() != value || value.abs() > 9_007_199_254_740_992.0 {
		return None;
	}
	// Not lossy: an integral double of magnitude <= 2^53 converts exactly.
	Some(value as i64)
}

/// An `i64` of magnitude at most 2^53 as a double (exact in that range;
/// callers pass time values and day counts).
#[allow(clippy::cast_precision_loss)]
const fn to_f64(value: i64) -> f64 {
	value as f64
}

/// Proleptic Gregorian year, month (1–12) and day for days since the epoch.
fn civil_from_days(days: i64) -> (i64, i64, i64) {
	let shifted = days + 719_468;
	let era = shifted.div_euclid(146_097);
	let day_of_era = shifted.rem_euclid(146_097);
	let year_of_era =
		(day_of_era - day_of_era / 1460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
	let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
	let month_index = (5 * day_of_year + 2) / 153;
	let day = day_of_year - (153 * month_index + 2) / 5 + 1;
	let month = if month_index < 10 {
		month_index + 3
	} else {
		month_index - 9
	};
	let year = year_of_era + era * 400 + i64::from(month <= 2);
	(year, month, day)
}

/// V8's `MakeDay` (ECMA-262 21.4.1.28) with its integer fast path.
fn make_day(year: f64, month: f64, date: f64) -> f64 {
	const MIN_YEAR: f64 = -1_000_000.0;
	const MAX_YEAR: f64 = 1_000_000.0;
	const MIN_MONTH: f64 = -10_000_000.0;
	const MAX_MONTH: f64 = 10_000_000.0;
	if !((MIN_YEAR..=MAX_YEAR).contains(&year)
		&& (MIN_MONTH..=MAX_MONTH).contains(&month)
		&& date.is_finite())
	{
		return f64::NAN;
	}
	let (Some(mut y), Some(mut m)) = (exact_i64(year.trunc()), exact_i64(month.trunc())) else {
		return f64::NAN;
	};
	y += m / 12;
	m %= 12;
	if m < 0 {
		m += 12;
		y -= 1;
	}
	const YEAR_DELTA: i64 = 399_999;
	const BASE_DAY: i64 = 365 * (1970 + YEAR_DELTA) + (1970 + YEAR_DELTA) / 4
		- (1970 + YEAR_DELTA) / 100
		+ (1970 + YEAR_DELTA) / 400;
	let shifted = y + YEAR_DELTA;
	let mut day_from_year = 365 * shifted + shifted / 4 - shifted / 100 + shifted / 400 - BASE_DAY;
	const COMMON: [i64; 12] = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];
	const LEAP: [i64; 12] = [0, 31, 60, 91, 121, 152, 182, 213, 244, 274, 305, 335];
	let table = if y % 4 != 0 || (y % 100 == 0 && y % 400 != 0) {
		&COMMON
	} else {
		&LEAP
	};
	day_from_year += usize::try_from(m)
		.ok()
		.and_then(|index| table.get(index))
		.copied()
		.unwrap_or_default();
	to_f64(day_from_year - 1) + date.trunc()
}

/// V8's `MakeTime`.
fn make_time(hour: f64, minute: f64, second: f64, milli: f64) -> f64 {
	if hour.is_finite() && minute.is_finite() && second.is_finite() && milli.is_finite() {
		hour.trunc() * 3_600_000.0
			+ minute.trunc() * 60_000.0
			+ second.trunc() * 1000.0
			+ milli.trunc()
	} else {
		f64::NAN
	}
}

/// V8's `MakeDate`.
fn make_date(day: f64, time: f64) -> f64 {
	if !day.is_finite() || !time.is_finite() {
		return f64::NAN;
	}
	if time == 0.0 && day != 0.0 {
		return day * MS_PER_DAY;
	}
	time + day * MS_PER_DAY
}

